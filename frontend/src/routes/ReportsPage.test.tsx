import { QueryClientProvider } from '@tanstack/react-query'
import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { http, HttpResponse } from 'msw'
import { MemoryRouter } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { queryClient } from '../lib/queryClient'
import { server } from '../test/mswServer'
import { ReportsPage } from './ReportsPage'

describe('ReportsPage', () => {
  beforeEach(() => {
    queryClient.clear()
  })

  it('shows a report with its table and links the PDF download', async () => {
    const summary = { id: 3, title: 'Network report', source: 'snapshot', created_at: '2026-10-09T01:00:00Z' }
    server.use(
      http.get('/api/reports', () => HttpResponse.json([summary])),
      http.get('/api/reports/3', () =>
        HttpResponse.json({ ...summary, content: '## Devices\n\n| Name | IP |\n|---|---|\n| pve1 | 10.0.0.5 |\n' }),
      ),
    )
    render(
      <MemoryRouter>
        <QueryClientProvider client={queryClient}>
          <ReportsPage />
        </QueryClientProvider>
      </MemoryRouter>,
    )
    expect(await screen.findByRole('cell', { name: 'pve1' })).toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'Download PDF' })).toHaveAttribute('href', '/api/reports/3/pdf')
    expect(screen.getByRole('link', { name: 'Download Markdown' })).toHaveAttribute(
      'href',
      '/api/reports/3/markdown',
    )
  })

  it('groups the per-network reports of a run under one run heading', async () => {
    const base = { source: 'run', run_id: 9, created_at: '2026-11-18T00:00:00Z' }
    const lab = { ...base, id: 11, title: 'Lab report, run #9', scope: 'Lab' }
    const dmz = { ...base, id: 12, title: 'DMZ report, run #9', scope: 'DMZ' }
    server.use(
      http.get('/api/reports', () => HttpResponse.json([lab, dmz])),
      http.get('/api/reports/11', () => HttpResponse.json({ ...lab, content: 'Lab body' })),
    )
    render(
      <MemoryRouter>
        <QueryClientProvider client={queryClient}>
          <ReportsPage />
        </QueryClientProvider>
      </MemoryRouter>,
    )

    expect(await screen.findAllByText('Run #9')).toHaveLength(1)
    expect(screen.getByText(/^Lab · /)).toBeInTheDocument()
    expect(screen.getByText(/^DMZ · /)).toBeInTheDocument()
  })

  it("shows which agent wrote a report, from source metadata, regardless of what the report's own text says", async () => {
    const summary = { id: 4, title: 'Pentest of 10.0.0.5', source: 'agent:tajonaso', created_at: '2026-11-17T00:00:00Z' }
    server.use(
      http.get('/api/reports', () => HttpResponse.json([summary])),
      http.get('/api/reports/4', () =>
        HttpResponse.json({ ...summary, content: 'Findings...\n\n*Generated by HexStrike AI*' }),
      ),
    )
    render(
      <MemoryRouter>
        <QueryClientProvider client={queryClient}>
          <ReportsPage />
        </QueryClientProvider>
      </MemoryRouter>,
    )

    expect(await screen.findByText('Generated by tajonaso')).toBeInTheDocument()
  })

  it('creates a snapshot report on demand', async () => {
    let created = false
    server.use(
      http.get('/api/reports', () => HttpResponse.json([])),
      http.post('/api/reports/snapshot', () => {
        created = true
        return HttpResponse.json({ id: 1, title: 'New', source: 'snapshot', created_at: '2026-10-09T01:00:00Z', content: 'x' }, { status: 201 })
      }),
      http.get('/api/reports/1', () =>
        HttpResponse.json({ id: 1, title: 'New', source: 'snapshot', created_at: '2026-10-09T01:00:00Z', content: 'x' }),
      ),
    )
    render(
      <MemoryRouter>
        <QueryClientProvider client={queryClient}>
          <ReportsPage />
        </QueryClientProvider>
      </MemoryRouter>,
    )
    await userEvent.click(await screen.findByRole('button', { name: 'Create report now' }))
    expect(await screen.findByRole('heading', { name: 'New' })).toBeInTheDocument()
    expect(created).toBe(true)
  })

  it('deletes all reports at once after confirming', async () => {
    const summary = { id: 3, title: 'Network report', source: 'snapshot', created_at: '2026-10-09T01:00:00Z' }
    let deletedAll = false
    vi.spyOn(window, 'confirm').mockReturnValue(true)
    server.use(
      http.get('/api/reports', () => HttpResponse.json(deletedAll ? [] : [summary])),
      http.get('/api/reports/3', () =>
        HttpResponse.json({ ...summary, content: '## Devices\n\n| Name | IP |\n|---|---|\n| pve1 | 10.0.0.5 |\n' }),
      ),
      http.delete('/api/reports', () => {
        deletedAll = true
        return new HttpResponse(null, { status: 204 })
      }),
    )
    render(
      <MemoryRouter>
        <QueryClientProvider client={queryClient}>
          <ReportsPage />
        </QueryClientProvider>
      </MemoryRouter>,
    )
    await userEvent.click(await screen.findByRole('button', { name: 'Delete all' }))
    expect(window.confirm).toHaveBeenCalled()
    await screen.findByText('No reports yet.')
  })
})
